def score_phase_completion(events: list[dict[str, Any]], *, success: bool) -> float | str:
    phase_events = [
        event
        for event in events
        if str(event.get("event", "")).startswith("ultra_phase_")
        or event.get("event") == "ultra_plan_complete"
    ]
    if not phase_events:
        return ""
    total = 0
    for event in phase_events:
        total = max(total, safe_int_event(event.get("total_phases")))
    phase_ids = [
        str(event.get("phase_id", ""))
        for event in phase_events
        if event.get("phase_id")
    ]
    if total <= 0:
        total = len(set(phase_ids))
    if total <= 0:
        return 100.0 if success else 0.0
    per_phase: dict[str, set[str]] = {}
    for event in phase_events:
        phase_id = str(event.get("phase_id", ""))
        if not phase_id:
            continue
        per_phase.setdefault(phase_id, set()).add(str(event.get("event", "")))
    completed = sum(1 for stages in per_phase.values() if "ultra_phase_complete" in stages)
    if success and completed >= total:
        return 100.0
    stage_weights = {
        "ultra_phase_start": 20.0,
        "ultra_phase_scaffold_complete": 20.0,
        "ultra_phase_execute_complete": 25.0,
        "ultra_phase_profile_check": 15.0,
        "ultra_phase_complete": 20.0,
    }
    phase_scores = []
    for phase_id in sorted(set(phase_ids)):
        stages = per_phase.get(phase_id, set())
        score = sum(weight for stage, weight in stage_weights.items() if stage in stages)
        phase_scores.append(clamp(score))
    while len(phase_scores) < total:
        phase_scores.append(0.0)
    return round(sum(phase_scores[:total]) / total, 1)


def score_phase_stage_scores(events: list[dict[str, Any]], *, success: bool) -> dict[str, float | str]:
    phase_events = [
        event
        for event in events
        if str(event.get("event", "")).startswith("ultra_phase_")
        or event.get("event") == "ultra_plan_complete"
    ]
    if not phase_events:
        return {
            "phase_plan_validity_score": "",
            "phase_scaffold_success_score": "",
            "phase_step_execution_score": "",
            "phase_verify_success_score": "",
            "phase_postcheck_success_score": "",
            "phase_finalization_score": "",
            "phase_failure_stage": "",
        }
    total = 0
    for event in phase_events:
        total = max(total, safe_int_event(event.get("total_phases")))
    phase_ids = sorted(
        {
            str(event.get("phase_id", ""))
            for event in phase_events
            if event.get("phase_id")
        }
    )
    if total <= 0:
        total = len(phase_ids)
    if total <= 0:
        total = 1
    per_phase: dict[str, set[str]] = {phase_id: set() for phase_id in phase_ids}
    failed_stages: list[str] = []
    for event in phase_events:
        phase_id = str(event.get("phase_id", ""))
        if phase_id:
            per_phase.setdefault(phase_id, set()).add(str(event.get("event", "")))
        if event.get("event") == "ultra_phase_failed":
            stage = str(event.get("stage", "") or "unknown")
            failed_stages.append(stage)
    while len(per_phase) < total:
        per_phase[f"missing-{len(per_phase) + 1}"] = set()

    def ratio_for(event_name: str) -> float:
        count = sum(1 for stages in per_phase.values() if event_name in stages)
        return round(100.0 * count / total, 1)

    completion_events = [event for event in events if event.get("event") == "completion_verify"]
    if completion_events:
        verify_success = 100.0 if any(bool(event.get("ok")) for event in completion_events) else 0.0
    else:
        verify_success = ratio_for("ultra_phase_profile_check")
    postcheck_events = load_postcheck_events_from_phase_events(events)
    if postcheck_events:
        postcheck_success = 100.0 if all(bool(event.get("ok", True)) for event in postcheck_events) else 0.0
    elif success:
        postcheck_success = 100.0
    else:
        postcheck_success = ""

    completed = ratio_for("ultra_phase_complete")
    if success:
        completed = 100.0
    has_explicit_plan_validation = any(
        "ultra_phase_plan_validated" in stages for stages in per_phase.values()
    )
    phase_plan_validity = (
        ratio_for("ultra_phase_plan_validated")
        if has_explicit_plan_validation
        else ratio_for("ultra_phase_scaffold_complete")
    )
    return {
        "phase_plan_validity_score": phase_plan_validity,
        "phase_scaffold_success_score": ratio_for("ultra_phase_scaffold_complete"),
        "phase_step_execution_score": ratio_for("ultra_phase_execute_complete"),
        "phase_verify_success_score": verify_success,
        "phase_postcheck_success_score": postcheck_success,
        "phase_finalization_score": completed,
        "phase_failure_stage": ";".join(dict.fromkeys(failed_stages)),
    }


def load_postcheck_events_from_phase_events(events: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [
        event
        for event in events
        if event.get("event") in {"postcheck_summary", "postcheck"}
    ]


def score_build_repair(events: list[dict[str, Any]]) -> dict[str, float | str]:
    completion_events = [
        event for event in events if event.get("event") == "completion_verify"
    ]
    build_events = [event for event in completion_events if is_build_verify_event(event)]
    if not build_events:
        return {
            "build_verify_pass_score": "",
            "build_repair_effectiveness_score": "",
            "compile_diagnostic_progress_score": "",
            "verify_repair_edit_score": "",
        }
    final_build_event = build_events[-1]
    build_pass = 100.0 if bool(final_build_event.get("ok")) else 0.0
    progress_events = [
        event
        for event in events
        if event.get("event") == "verify_repair_progress"
    ]
    repair_turns = [
        event for event in events if event.get("event") == "verify_repair_turn"
    ]
    verdict_scores = [
        VERIFY_REPAIR_VERDICT_SCORE.get(str(event.get("verdict", "")).lower(), 0.0)
        for event in progress_events
    ]
    if bool(final_build_event.get("ok")):
        diagnostic_progress = 100.0
    elif verdict_scores:
        diagnostic_progress = round(sum(verdict_scores) / len(verdict_scores), 1)
    else:
        diagnostic_progress = 20.0

    had_edit = any(bool(event.get("had_edit")) for event in progress_events)
    had_no_edit_turn = any(event.get("has_edit") is False for event in repair_turns)
    if had_edit:
        repair_edit = 100.0
    elif had_no_edit_turn:
        repair_edit = 0.0
    else:
        repair_edit = 50.0

    if bool(final_build_event.get("ok")):
        effectiveness = 100.0
    else:
        effectiveness = round(0.60 * diagnostic_progress + 0.40 * repair_edit, 1)
        effectiveness = min(effectiveness, 70.0)
    return {
        "build_verify_pass_score": round(build_pass, 1),
        "build_repair_effectiveness_score": round(clamp(effectiveness), 1),
        "compile_diagnostic_progress_score": round(clamp(diagnostic_progress), 1),
        "verify_repair_edit_score": round(clamp(repair_edit), 1),
    }


def score_build_lifecycle(events: list[dict[str, Any]]) -> dict[str, float | str]:
    completion_events = [
        event for event in events if event.get("event") == "completion_verify"
    ]
    if not completion_events:
        step_bridge = score_step_runtime_bridge(events)
        repair_followthrough = score_repair_target_followthrough(events)
        return {
            "build_verifier_completion_score": "",
            "dependency_setup_boundary_score": "",
            "dependency_setup_bridge_score": "",
            "build_verifier_lifecycle_score": "",
            "profile_repair_symmetry_score": "",
            "step_runtime_bridge_score": round(step_bridge, 1)
            if isinstance(step_bridge, (int, float))
            else "",
            "repair_target_followthrough_score": round(repair_followthrough, 1)
            if isinstance(repair_followthrough, (int, float))
            else "",
            "repair_target_resolution_score": "",
            "repair_stagnation_score": "",
            "profile_static_vs_build_gap_score": "",
        }
    observations = []
    for event in completion_events:
        for observation in event.get("build_verifier_observations", []) or []:
            if isinstance(observation, dict):
                observations.append(observation)
    build_required = any(bool(event.get("build_verifier_required")) for event in completion_events)
    build_required = build_required or bool(observations)
    stop = next((event for event in reversed(events) if event.get("event") == "loop_stop"), {})
    stop_reason = str(stop.get("reason", ""))
    final_event = completion_events[-1]
    final_ok = bool(final_event.get("ok"))
    final_observations = [
        observation
        for observation in final_event.get("build_verifier_observations", []) or []
        if isinstance(observation, dict)
    ]
    final_statuses = [
        str(observation.get("status", ""))
        for observation in final_observations
        if observation.get("required_for_completion", True)
    ]
    final_lifecycles = [
        lifecycle
        for lifecycle in final_event.get("build_verifier_lifecycle", []) or []
        if isinstance(lifecycle, dict)
    ]
    lifecycle_statuses = [
        str(lifecycle.get("final_status", ""))
        for lifecycle in final_lifecycles
        if (lifecycle.get("requirement") or {}).get("required_for_completion", True)
    ]
    setup_statuses = [
        str((lifecycle.get("setup") or {}).get("status", ""))
        for lifecycle in final_lifecycles
        if isinstance(lifecycle.get("setup"), dict)
    ]
    if lifecycle_statuses:
        final_statuses = lifecycle_statuses

    if not build_required:
        build_completion: float | str = ""
        dependency_boundary: float | str = ""
        profile_gap: float | str = ""
        setup_bridge: float | str = ""
        lifecycle_score: float | str = ""
    elif final_statuses and all(status == "passed" for status in final_statuses):
        build_completion = 100.0
        dependency_boundary = 100.0
        profile_gap = 100.0
        setup_bridge = 100.0
        lifecycle_score = 100.0
    elif "dependency_missing" in final_statuses:
        build_completion = 30.0
        dependency_boundary = 85.0
        setup_bridge = 55.0
        profile_gap = 70.0
        lifecycle_score = 35.0
    elif "policy_rejected" in final_statuses:
        build_completion = 0.0
        dependency_boundary = 20.0
        setup_bridge = 20.0
        profile_gap = 60.0
        lifecycle_score = 10.0
    elif "blocked" in final_statuses:
        build_completion = 20.0
        dependency_boundary = 60.0
        setup_bridge = 45.0
        profile_gap = 70.0
        lifecycle_score = 25.0
    elif "failed" in final_statuses:
        build_completion = 40.0
        dependency_boundary = 90.0
        setup_bridge = 100.0 if "passed" in setup_statuses else 70.0
        profile_gap = 80.0
        lifecycle_score = 55.0 if "passed" in setup_statuses else 45.0
    elif final_ok:
        build_completion = 0.0
        dependency_boundary = 0.0
        setup_bridge = 0.0
        profile_gap = 0.0
        lifecycle_score = 0.0
    else:
        build_completion = 50.0
        dependency_boundary = 60.0
        setup_bridge = 60.0
        profile_gap = 60.0
        lifecycle_score = 50.0
    if setup_statuses:
        if any(status in {"failed", "timed_out"} for status in setup_statuses):
            setup_bridge = min_score(setup_bridge, 25.0)
        elif any(status == "blocked" for status in setup_statuses):
            setup_bridge = min_score(setup_bridge, 45.0)
        elif any(status == "passed" for status in setup_statuses):
            setup_bridge = max_score(setup_bridge, 90.0)

    repair_targets = [
        str(event.get("repair_target", ""))
        for event in completion_events
        if event.get("repair_target")
    ]
    if final_ok:
        repair_target_resolution = 100.0
    elif stop_reason == "repair_target_misdirected":
        repair_target_resolution = 0.0
    elif repair_targets and repair_targets[-1] != "unknown":
        repair_target_resolution = 70.0
    elif repair_targets:
        repair_target_resolution = 40.0
    else:
        repair_target_resolution = ""

    progress_events = [
        event for event in events if event.get("event") == "verify_repair_progress"
    ]
    if final_ok:
        repair_stagnation = 100.0
    elif stop_reason in {
        "verify_repair_no_change",
        "repair_stagnation",
        "verify_repair_progress_unchanged",
        "verify_repair_progress_regressed",
        "verify_repair_progress_invalid",
    }:
        repair_stagnation = 20.0
    elif any(str(event.get("verdict", "")) == "improved" for event in progress_events):
        repair_stagnation = 75.0
    elif progress_events:
        repair_stagnation = 50.0
    else:
        repair_stagnation = 70.0

    step_bridge = score_step_runtime_bridge(events)
    repair_followthrough = score_repair_target_followthrough(events)
    profile_symmetry = score_profile_repair_symmetry(completion_events, final_ok=final_ok)

    return {
        "build_verifier_completion_score": round(build_completion, 1)
        if isinstance(build_completion, (int, float))
        else "",
        "dependency_setup_boundary_score": round(dependency_boundary, 1)
        if isinstance(dependency_boundary, (int, float))
        else "",
        "dependency_setup_bridge_score": round(setup_bridge, 1)
        if isinstance(setup_bridge, (int, float))
        else "",
        "build_verifier_lifecycle_score": round(lifecycle_score, 1)
        if isinstance(lifecycle_score, (int, float))
        else "",
        "profile_repair_symmetry_score": round(profile_symmetry, 1)
        if isinstance(profile_symmetry, (int, float))
        else "",
        "step_runtime_bridge_score": round(step_bridge, 1)
        if isinstance(step_bridge, (int, float))
        else "",
        "repair_target_followthrough_score": round(repair_followthrough, 1)
        if isinstance(repair_followthrough, (int, float))
        else "",
        "repair_target_resolution_score": round(repair_target_resolution, 1)
        if isinstance(repair_target_resolution, (int, float))
        else "",
        "repair_stagnation_score": round(repair_stagnation, 1)
        if isinstance(repair_stagnation, (int, float))
        else "",
        "profile_static_vs_build_gap_score": round(profile_gap, 1)
        if isinstance(profile_gap, (int, float))
        else "",
    }


def score_step_runtime_bridge(events: list[dict[str, Any]]) -> float | str:
    step_events = [
        event
        for event in events
        if event.get("event") in {"step_verify_failure", "step_verify_repair"}
    ]
    if not step_events:
        return ""
    if any(event.get("event") == "step_verify_repair" and event.get("ok") is True for event in step_events):
        return 100.0
    score = 80.0
    for event in step_events:
        dependency_missing = bool(event.get("dependency_missing"))
        authority = str(event.get("dependency_setup_authority", ""))
        if dependency_missing and authority in {"none", ""}:
            score -= 35.0
        elif dependency_missing:
            score -= 20.0
        if event.get("event") == "step_verify_repair" and event.get("repair_target_followed") is False:
            score -= 25.0
    return clamp(score)


def score_repair_target_followthrough(events: list[dict[str, Any]]) -> float | str:
    repair_events = [
        event
        for event in events
        if event.get("event") == "step_verify_repair"
        and event.get("repair_target_followed") is not None
    ]
    if not repair_events:
        return ""
    followed = sum(1 for event in repair_events if event.get("repair_target_followed") is True)
    return round(100.0 * followed / len(repair_events), 1)


def score_profile_repair_symmetry(
    completion_events: list[dict[str, Any]], *, final_ok: bool
) -> float | str:
    profile_events = [
        event
        for event in completion_events
        if event.get("profile_failures") or str(event.get("repair_target", "")) in {"package_config", "framework_config"}
    ]
    if not profile_events:
        return ""
    if final_ok:
        return 100.0
    final = profile_events[-1]
    failures = " ".join(str(item) for item in final.get("profile_failures", []) or []).lower()
    if any(token in failures for token in ["dependency", "typescript", "react", "next", "scripts.build"]):
        return 35.0
    if any(token in failures for token in ["tsconfig", "css", "layout", "use client"]):
        return 50.0
    return 65.0


def score_plan_run_success_predictor(
    *,
    bridge_scores: dict[str, float | str],
    build_lifecycle_scores: dict[str, float | str],
    finalization_scores: dict[str, float | str],
    runtime_friction: float,
) -> float | str:
    candidates: list[float] = [float(runtime_friction)]
    for source, key in [
        (bridge_scores, "execution_contract_adherence_score"),
        (build_lifecycle_scores, "dependency_setup_bridge_score"),
        (build_lifecycle_scores, "build_verifier_lifecycle_score"),
        (build_lifecycle_scores, "step_runtime_bridge_score"),
        (build_lifecycle_scores, "repair_target_followthrough_score"),
        (finalization_scores, "finalization_score"),
    ]:
        value = source.get(key)
        if isinstance(value, (int, float)):
            candidates.append(float(value))
    if not candidates:
        return ""
    mean_score = sum(candidates) / len(candidates)
    min_score_value = min(candidates)
    cap = 100.0
    if min_score_value < 40.0:
        cap = 55.0
    elif min_score_value < 60.0:
        cap = 70.0
    return round(min(mean_score, cap), 1)


def min_score(value: float | str, cap: float) -> float:
    if isinstance(value, (int, float)):
        return min(float(value), cap)
    return cap


def max_score(value: float | str, floor: float) -> float:
    if isinstance(value, (int, float)):
        return max(float(value), floor)
    return floor


def is_build_verify_event(event: dict[str, Any]) -> bool:
    text_parts = [
        str(event.get("primary_reason", "")),
        str(event.get("failure_signature", "")),
        str(event.get("dependency_setup_status", "")),
    ]
    if event.get("build_verifier_required"):
        return True
    for status in event.get("build_verifier_statuses", []) or []:
        text_parts.append(str(status))
    for observation in event.get("build_verifier_observations", []) or []:
        if isinstance(observation, dict):
            text_parts.append(str(observation.get("command", "")))
            text_parts.append(str(observation.get("status", "")))
            text_parts.append(str(observation.get("primary_reason", "")))
    for requirement in event.get("deferred_verify_requirements", []) or []:
        if isinstance(requirement, dict):
            text_parts.append(str(requirement.get("command", "")))
            text_parts.append(str(requirement.get("status", "")))
        else:
            text_parts.append(str(requirement))
    text = " ".join(text_parts).lower()
    if any(marker in text for marker in BUILD_VERIFY_MARKERS):
        return True
    if int(event.get("command_failures") or 0) > 0:
        return any(marker in text for marker in ("build", "tsc", ".tsx", ".ts", "next"))
    return False


def score_prompt_contract(events: list[dict[str, Any]]) -> float | str:
    contract_events = [
        event for event in events if event.get("event") == "step_prompt_contract"
    ]
    if not contract_events:
        return ""
    scores = []
    for event in contract_events:
        checks = [
            bool(event.get("has_overall_goal")),
            bool(event.get("has_required_final_artifacts")),
            bool(event.get("has_expected_paths")),
            bool(event.get("has_verify_commands")),
            bool(event.get("has_expected_result")),
            bool(event.get("has_bounded_repair_policy")),
            event.get("prompt_body_saved") is False,
        ]
        if event.get("prior_artifact_context_applicable"):
            checks.append(bool(event.get("has_prior_artifact_context")))
        scores.append(100.0 * sum(1 for check in checks if check) / len(checks))
    return round(sum(scores) / len(scores), 1)


def score_step_obligation_scope(events: list[dict[str, Any]]) -> tuple[float | str, int | str]:
    scope_events = [
        event
        for event in events
        if event.get("event") == "step_obligation_scope"
        and event.get("session_scope") == "plan-run-step"
    ]
    if not scope_events:
        return "", ""
    scores = []
    violations = 0
    for event in scope_events:
        explicit = [str(path) for path in event.get("explicit_required_paths", []) or []]
        effective = [str(path) for path in event.get("effective_required_paths", []) or []]
        prompt_extracted = [
            str(path) for path in event.get("prompt_extracted_paths", []) or []
        ]
        contract_paths = [
            str(path) for path in event.get("completion_contract_paths", []) or []
        ]
        extraction_enabled = bool(event.get("prompt_extracted_paths_enabled"))
        contract_merge_enabled = bool(event.get("completion_contract_path_merge_enabled"))
        contract_verify_enabled = bool(event.get("completion_contract_verification_enabled"))
        score = 100.0
        if extraction_enabled:
            score -= 30.0 if prompt_extracted else 15.0
        if contract_merge_enabled:
            score -= 30.0 if contract_paths else 15.0
        if contract_verify_enabled:
            score -= 20.0
        if effective != explicit:
            score -= 30.0
        score = clamp(score)
        if score < 100.0:
            violations += 1
        scores.append(score)
    return round(sum(scores) / len(scores), 1), violations


def clamp(value: float) -> float:
    return max(0.0, min(100.0, value))


def safe_int_event(value: object) -> int:
    try:
        return int(str(value))
    except (TypeError, ValueError):
        return 0
