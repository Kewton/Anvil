WRITE_TOOLS = {"Write", "Edit", "MultiEdit"}
INSPECTION_TOOLS = {"Read", "Glob", "Grep"}
BUILD_VERIFY_MARKERS = (
    "npm run build",
    "pnpm build",
    "yarn build",
    "next build",
    "cargo build",
    "tsc",
)
DEPENDENCY_MUTATION_LOG_PATTERNS = (
    "installing dependencies",
    "installing devdependencies",
    "added packages",
    "yarn add",
)
LOCKFILE_MUTATION_LOG_PATTERNS = (
    "lockfile was successfully patched",
    "found lockfile missing swc dependencies",
)
PACKAGE_MANAGER_MIX_LOG_PATTERNS = (
    "lock files generated by tools other than yarn",
    "package-lock.json found",
)
